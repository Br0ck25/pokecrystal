export const JOHTO_PALETTE_MAP_GAP = Object.freeze(Array(16).fill('UNUSED'));

/** Return the source palette label for a tilepal group/index, or null if absent. */
export function getJohtoTilePalette(tileset, tileIndex) {
  if (!Number.isInteger(tileset) || !Number.isInteger(tileIndex) || tileset < 0 || tileIndex < 0) return null;
  return JOHTO_TILE_PALETTE_MAP[tileset]?.[tileIndex] ?? null;
}
